import { PrismaClient } from '../lib/generated/prisma/client.js';
import { PrismaPg } from '@prisma/adapter-pg';
import dotenv from 'dotenv';
dotenv.config({ path: '.env.local' });
dotenv.config({ path: '.env' });
const adapter = new PrismaPg({ connectionString: process.env.DATABASE_URL, ssl: process.env.DATABASE_URL.includes('localhost') ? false : { rejectUnauthorized: false } });
const p = new PrismaClient({ adapter });
const tenant = await p.tenant.findFirst({ where: { slug: 'mi-pollo' } });
console.log('Tenant mi-pollo:', tenant?.id, tenant?.slug);
const inTenant = await p.adminUser.findMany({ where: { tenantId: tenant?.id }, select: { id: true, username: true, name: true, role: true, tenantId: true } });
console.log(`\n→ AdminUsers asignados al tenant mi-pollo: ${inTenant.length}`);
console.table(inTenant);
const all = await p.adminUser.findMany({ select: { id: true, username: true, name: true, tenantId: true, role: true } });
console.log(`\n→ Total adminUsers en DB: ${all.length}`);
const byTenant = {};
for (const u of all) byTenant[u.tenantId || 'NULL/orphan'] = (byTenant[u.tenantId || 'NULL/orphan'] || 0) + 1;
console.log('→ Conteo por tenantId:');
console.table(byTenant);
const tenants = await p.tenant.findMany({ select: { id: true, slug: true, name: true } });
console.log('\n→ Tenants existentes:');
console.table(tenants);
await p.$disconnect();
